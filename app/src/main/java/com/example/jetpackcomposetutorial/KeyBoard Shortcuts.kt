package com.example.jetpackcomposetutorial

// Here we are going to write all the shortcuts for android studio

/*
* --- GENERAL & NAVIGATION ---
* Double Shift           : Search Everywhere
* Ctrl + Shift + A       : Find Action
* Ctrl + E               : Recent Files
* Ctrl + Shift + E       : Recently Edited Files
* Ctrl + N               : Find Class
* Ctrl + Shift + N       : Find File
* Alt + 1                : Project Window
* Esc                    : Focus back to Editor
*
* --- EDITING ---
* Ctrl + D               : To duplicate the line
* Ctrl + Y               : Delete current line
* Ctrl + Alt + L         : Reformat Code
* Ctrl + Alt + O         : Optimize Imports
* Alt + Enter            : Show Context Actions (Quick Fix)
* Ctrl + Space           : Basic Code Completion
* Ctrl + Shift + Space   : Smart Code Completion
* Ctrl + /               : Comment/Uncomment with line comment
* Ctrl + Shift + /       : Comment/Uncomment with block comment
* Ctrl + Alt + I         : Auto-indent lines
* Ctrl + Shift + V       : Paste from History
*
* --- REFACTORING ---
* Shift + F6             : Rename
* Ctrl + Alt + M         : Extract Method
* Ctrl + Alt + V         : Extract Variable
* Ctrl + Alt + F         : Extract Field
* Ctrl + Alt + C         : Extract Constant
* Ctrl + Alt + P         : Extract Parameter
*
* --- SEARCH & REPLACE ---
* Ctrl + F               : Find in current file
* Ctrl + R               : Replace in current file
* Ctrl + Shift + F       : Find in Path (Project Search)
* Ctrl + Shift + R       : Replace in Path
*
* --- NAVIGATION INSIDE CODE ---
* Ctrl + B               : Go to Declaration
* Ctrl + Alt + B         : Go to Implementation(s)
* Alt + F7               : Find Usages
* Ctrl + G               : Go to Line
* Ctrl + F12             : File Structure (Method list)
*
* --- BUILD & RUN ---
* Shift + F10            : Run
* Shift + F9             : Debug
* Ctrl + F9              : Make Project
*
* --- JETPACK COMPOSE ---
* Ctrl + Alt + Shift + P : Refresh Compose Preview
*/
